const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('workbench', {

  agentProbe: (...args) => ipcRenderer.invoke('agent-probe', ...args),
  claudeHelp: () => ipcRenderer.invoke('claude-help'),
  claudeAuthStatus: id => ipcRenderer.invoke('claude-auth-status', id),
  codexUsage: () => ipcRenderer.invoke('codex-usage'),
  resources: () => ipcRenderer.invoke('resource-snapshot'),
  sleepMode: mode => ipcRenderer.invoke('sleep-mode', mode),
  onSleepState: callback => ipcRenderer.on('sleep-state', (_, state) => callback(state)),
  agentBrowse: () => ipcRenderer.invoke('agent-browse'),
  chatConnect: task => ipcRenderer.invoke('chat-connect', task),
  chatSend: (...args) => ipcRenderer.invoke('chat-send', ...args),
  chatStop: id => ipcRenderer.invoke('chat-stop', id),
  chatApprove: (...args) => ipcRenderer.invoke('chat-approve', ...args),
  chatClose: id => ipcRenderer.invoke('chat-close', id),
  onChat: callback => ipcRenderer.on('chat-event', (_, id, event) => callback(id, event)),
  gitStatus: cwd => ipcRenderer.invoke('git-status', cwd),
  gitDiff: (...args) => ipcRenderer.invoke('git-diff', ...args),
  githubPulls: (...args) => ipcRenderer.invoke('github-pulls', ...args),
  gitFileHistory: (...args) => ipcRenderer.invoke('git-file-history', ...args),
  githubDetails: (...args) => ipcRenderer.invoke('github-pr-details', ...args),
  gitCommitDetails: (...args) => ipcRenderer.invoke('git-commit-details', ...args),
  gitWorktrees: cwd => ipcRenderer.invoke('git-worktrees', cwd),
  gitCreateWorktree: (...args) => ipcRenderer.invoke('git-create-worktree', ...args),
  gitStage: (cwd, names) => ipcRenderer.invoke('git-stage', cwd, names),
  gitUnstage: (cwd, names) => ipcRenderer.invoke('git-unstage', cwd, names),
  gitStageAll: cwd => ipcRenderer.invoke('git-stage-all', cwd),
  gitCommit: (cwd, message) => ipcRenderer.invoke('git-commit', cwd, message),
  gitPush: cwd => ipcRenderer.invoke('git-push', cwd),
  githubPrDraft: cwd => ipcRenderer.invoke('github-pr-draft', cwd),
  githubPrCreate: (cwd, request) => ipcRenderer.invoke('github-pr-create', cwd, request),
  aiCommitMessage: (cwd, provider) => ipcRenderer.invoke('ai-commit-message', cwd, provider),
  notify: notification => ipcRenderer.invoke('notify', notification),
  onNotificationOpen: callback => ipcRenderer.on('notification-open', (_, taskId) => callback(taskId)),
  githubPrFeedback: cwd => ipcRenderer.invoke('github-pr-feedback', cwd),
  githubCheckLog: (cwd, detailsUrl) => ipcRenderer.invoke('github-check-log', cwd, detailsUrl),
  readState: () => ipcRenderer.sendSync('state-read'),
  writeState: values => ipcRenderer.invoke('state-write', values),
  flushState: values => ipcRenderer.sendSync('state-flush', values),
  taskWorktreeCreate: (cwd, name, id) => ipcRenderer.invoke('task-worktree-create', cwd, name, id),
  taskWorktreeRemove: (id, directory, branch, force, base) => ipcRenderer.invoke('task-worktree-remove', id, directory, branch, force, base),
  openLocalPreview: address => ipcRenderer.invoke('open-local-preview', address),
  gitLineBlame: (...args) => ipcRenderer.invoke('git-line-blame', ...args),
  githubOpen: (...args) => ipcRenderer.invoke('github-open', ...args),

  home: () => ipcRenderer.invoke('home'),
  folder: () => ipcRenderer.invoke('folder'),
  spawn: (...args) => ipcRenderer.invoke('spawn', ...args),
  input: (id, value) => ipcRenderer.invoke('input', id, value),
  resize: (...args) => ipcRenderer.invoke('resize', ...args),
  close: id => ipcRenderer.invoke('close-terminal', id),
  copy: text => ipcRenderer.invoke('copy', text),
  save: text => ipcRenderer.invoke('save', text),
  openMarkdownNote: cwd => ipcRenderer.invoke('open-markdown-note', cwd),
  saveMarkdownNote: (...args) => ipcRenderer.invoke('save-markdown-note', ...args),
  onData: callback => ipcRenderer.on('terminal-data', (_, id, value) => callback(id, value)),
  onExit: callback => ipcRenderer.on('terminal-exit', (_, id, value) => callback(id, value))
});
